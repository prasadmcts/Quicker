/*
  Interviewer Personalised Availability - Multiple Windows per Day
  =================================================================
  Scope: recurring weekly availability and unavailability preferences only.
  This script does NOT check any external calendar.

  Replace INTERVIEWER_MASTER with the actual existing parent table name.
  Assumes the parent table has a primary/unique key on:
      (INTERVIEWER_SID, ORACLE_CAND_ID)
  The parent rows ('SID_MULTI','CAND_MULTI') must exist before running inserts.

  Day of week: Monday=1, Tuesday=2, Wednesday=3, Thursday=4,
               Friday=5, Saturday=6, Sunday=7.
  Times are minutes after midnight. Intervals are [start, end):
      08:00 = 480, 10:00 = 600, 14:00 = 840, 17:00 = 1020,
      22:00 = 1320, 24:00/end of day = 1440, 01:00 = 60.

  Multiple windows on the same day are stored as multiple rows.
*/


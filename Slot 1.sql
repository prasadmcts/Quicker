/* -----------------------------------------------------------------
   2. CREATE PREFERENCE TABLE
   ----------------------------------------------------------------- */
CREATE TABLE INTERVIEWER_PREFERENCE_SLOT (
    SLOT_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    INTERVIEWER_SID   VARCHAR2(100) NOT NULL,
    ORACLE_CAND_ID    VARCHAR2(100) NOT NULL,
    DAY_OF_WEEK       NUMBER(1) NOT NULL,
    START_MINUTE      NUMBER(4) NOT NULL,
    END_MINUTE        NUMBER(4) NOT NULL,
    IS_AVAILABLE      NUMBER(1) NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_INTERVIEWER_PREF_SLOT PRIMARY KEY (SLOT_ID),
    CONSTRAINT FK_INTERVIEWER_PREF_SLOT
        FOREIGN KEY (INTERVIEWER_SID, ORACLE_CAND_ID)
        REFERENCES INTERVIEWER_MASTER (INTERVIEWER_SID, ORACLE_CAND_ID)
        ON DELETE CASCADE,
    CONSTRAINT CK_PREF_SLOT_DAY CHECK (DAY_OF_WEEK BETWEEN 1 AND 7),
    CONSTRAINT CK_PREF_SLOT_START CHECK (START_MINUTE BETWEEN 0 AND 1439),
    CONSTRAINT CK_PREF_SLOT_END CHECK (END_MINUTE BETWEEN 1 AND 1440),
    CONSTRAINT CK_PREF_SLOT_RANGE CHECK (END_MINUTE > START_MINUTE),
    CONSTRAINT CK_PREF_SLOT_AVAILABLE CHECK (IS_AVAILABLE IN (0, 1)),
    CONSTRAINT UQ_PREF_SLOT UNIQUE (
        INTERVIEWER_SID, ORACLE_CAND_ID, DAY_OF_WEEK,
        START_MINUTE, END_MINUTE, IS_AVAILABLE
    )
);

CREATE INDEX IDX_PREF_SLOT_LOOKUP
ON INTERVIEWER_PREFERENCE_SLOT (
    INTERVIEWER_SID, ORACLE_CAND_ID, DAY_OF_WEEK,
    START_MINUTE, END_MINUTE, IS_AVAILABLE
);


/* -----------------------------------------------------------------
   4. SELECT PREFERENCE RULES
   Shows multiple windows as multiple rows.
   ----------------------------------------------------------------- */
SELECT
    CASE DAY_OF_WEEK
        WHEN 1 THEN 'MONDAY'
        WHEN 2 THEN 'TUESDAY'
        WHEN 3 THEN 'WEDNESDAY'
        WHEN 4 THEN 'THURSDAY'
        WHEN 5 THEN 'FRIDAY'
        WHEN 6 THEN 'SATURDAY'
        WHEN 7 THEN 'SUNDAY'
    END AS DAY_NAME,
    DAY_OF_WEEK,
    CASE
        WHEN START_MINUTE = 0 THEN '12:00 AM'
        ELSE TO_CHAR(DATE '2000-01-01' + START_MINUTE / 1440, 'HH:MI AM')
    END AS START_TIME,
    CASE
        WHEN END_MINUTE = 1440 THEN '12:00 AM (next day boundary)'
        ELSE TO_CHAR(DATE '2000-01-01' + END_MINUTE / 1440, 'HH:MI AM')
    END AS END_TIME,
    IS_AVAILABLE,
    CASE IS_AVAILABLE WHEN 1 THEN 'AVAILABLE' ELSE 'UNAVAILABLE' END AS RULE_TYPE
FROM INTERVIEWER_PREFERENCE_SLOT
WHERE INTERVIEWER_SID = 'SID_MULTI'
  AND ORACLE_CAND_ID = 'CAND_MULTI'
ORDER BY DAY_OF_WEEK, START_MINUTE, END_MINUTE;

/* -----------------------------------------------------------------

/*
  IMPORTANT CROSS-MIDNIGHT NOTE:
  This schema intentionally stores each row within one day (END_MINUTE <= 1440).
  If the intention is Friday 22:00-midnight followed by Saturday 01:00-10:00,
  change the 01:00-10:00 row's DAY_OF_WEEK from 5 (Friday) to 6 (Saturday).
  A recurring Friday night does not make Saturday-morning hours part of Friday.
*/

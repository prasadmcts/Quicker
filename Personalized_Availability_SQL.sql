CREATE OR REPLACE TRIGGER TRG_INTERVIEWER_PREF_SLOT_BU
BEFORE UPDATE ON INTERVIEWER_PREFERENCE_SLOT
FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := SYSTIMESTAMP;
END;

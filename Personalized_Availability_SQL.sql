-- 14. GENERATE PERSONALIZED CANDIDATE START TIMES FOR A SELECTED DATE.
-- Binds: :interviewerSid, :oracleCandId, :dayOfWeek,
--        :durationMinutes, :slotStepMinutes.
-- durationMinutes examples: 30, 45, 60, 120.
-- slotStepMinutes is the gap between consecutive start times. Set it equal
-- to durationMinutes to produce the examples in the design document.
-- Keep the two values separate if a different start-time cadence is needed.
-- Java must validate both values are positive and <= 1440.
------------------------------------------------------------------------
WITH slot_offsets AS (
    SELECT LEVEL - 1 AS N
    FROM DUAL
    CONNECT BY LEVEL <= CEIL(1440 / :slotStepMinutes)
), candidate_slots AS (
    SELECT p.INTERVIEWER_SID,
           p.ORACLE_CAND_ID,
           p.DAY_OF_WEEK,
           p.START_MINUTE + (o.N * :slotStepMinutes) AS CANDIDATE_START,
           p.START_MINUTE + (o.N * :slotStepMinutes)
               + :durationMinutes AS CANDIDATE_END
    FROM INTERVIEWER_PREFERENCE_SLOT p
    CROSS JOIN slot_offsets o
    WHERE p.INTERVIEWER_SID = :interviewerSid
      AND p.ORACLE_CAND_ID = :oracleCandId
      AND p.DAY_OF_WEEK = :dayOfWeek
      AND p.IS_AVAILABLE = 1
      AND p.START_MINUTE + (o.N * :slotStepMinutes)
              + :durationMinutes <= p.END_MINUTE
), eligible_slots AS (
    SELECT DISTINCT c.CANDIDATE_START,
                    c.CANDIDATE_END
    FROM candidate_slots c
    WHERE NOT EXISTS (
        SELECT 1
        FROM INTERVIEWER_PREFERENCE_SLOT b
        WHERE b.INTERVIEWER_SID = :interviewerSid
          AND b.ORACLE_CAND_ID = :oracleCandId
          AND b.DAY_OF_WEEK = :dayOfWeek
          AND b.IS_AVAILABLE = 0
          AND b.START_MINUTE < c.CANDIDATE_END
          AND b.END_MINUTE > c.CANDIDATE_START
    )
)
SELECT CANDIDATE_START,
       CANDIDATE_END
FROM eligible_slots
ORDER BY CANDIDATE_START;


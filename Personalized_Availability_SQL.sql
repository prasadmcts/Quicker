------------------------------------------------------------------------
-- 12. CHECK ONE REQUESTED INTERVAL.
-- Binds: :interviewerSid, :oracleCandId, :dayOfWeek,
--        :requestedStartMinute, :requestedEndMinute.
-- The interval must fit wholly within one allowed window and must not
-- overlap a blocked interval. Intervals are [start, end).
------------------------------------------------------------------------
SELECT CASE
         WHEN EXISTS (
             SELECT 1
             FROM INTERVIEWER_PREFERENCE_SLOT p
             WHERE p.INTERVIEWER_SID = :interviewerSid
               AND p.ORACLE_CAND_ID = :oracleCandId
               AND p.DAY_OF_WEEK = :dayOfWeek
               AND p.IS_AVAILABLE = 1
               AND p.START_MINUTE <= :requestedStartMinute
               AND p.END_MINUTE >= :requestedEndMinute
         )
         AND NOT EXISTS (
             SELECT 1
             FROM INTERVIEWER_PREFERENCE_SLOT p
             WHERE p.INTERVIEWER_SID = :interviewerSid
               AND p.ORACLE_CAND_ID = :oracleCandId
               AND p.DAY_OF_WEEK = :dayOfWeek
               AND p.IS_AVAILABLE = 0
               AND p.START_MINUTE < :requestedEndMinute
               AND p.END_MINUTE > :requestedStartMinute
         )
         THEN 'PASS'
         ELSE 'REJECT'
       END AS PREFERENCE_RESULT
FROM DUAL;

